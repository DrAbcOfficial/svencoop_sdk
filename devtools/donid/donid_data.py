import argparse
import ast
import base64
import csv
import gzip
import io
import re
import sys
import zlib
from pathlib import Path

SYMBOL = "g_szPlayerExtrasList"
HEADER_PARTS = re.compile(r'"(?:\\.|[^"\\])*"|/\*[\s\S]*?\*/|//[^\r\n]*|\S')


def read_literal(text, symbol=SYMBOL):
    entry = re.search(r"\b" + re.escape(symbol) + r"\s*\[\s*\]\s*=", text)
    if not entry:
        raise ValueError(f"Cannot find {symbol} in the header")

    strings = []
    for match in HEADER_PARTS.finditer(text, entry.end()):
        part = match.group()
        if part.startswith(("//", "/*")):
            continue

        if part == ";":
            if not strings:
                raise ValueError(f"No text found for {symbol}")

            return "".join(strings).encode("ascii")

        if not part.startswith('"'):
            raise ValueError(f"Expected quoted text for {symbol}")

        try:
            strings.append(ast.literal_eval(part))
        except (SyntaxError, ValueError) as error:
            raise ValueError(f"Invalid quoted text for {symbol}") from error

    raise ValueError(f"Missing semicolon after {symbol}")


def decode_header(text, symbol=SYMBOL):
    encoded = b"".join(read_literal(text, symbol).split())
    padding = encoded.find(b"=")

    # Some headers contain extra text after Base64 data
    if padding >= 0:
        end = padding + 1
        while end < len(encoded) and encoded[end] == ord("="):
            end += 1

        encoded = encoded[:end]

    data = gzip.decompress(base64.b64decode(encoded, validate=True))
    describe_csv(data)
    return data


def check_row(row, number):
    if len(row) != 4:
        raise ValueError(f"Row {number}: expected four columns")

    if not row[0]:
        raise ValueError(f"Row {number}: authID is empty")

    try:
        level = int(row[3])
    except ValueError as error:
        raise ValueError(f"Row {number}: level must be a whole number") from error

    if not -1 <= level <= 6:
        raise ValueError(f"Row {number}: level must be -1 through 6")

    return level


def describe_csv(data):
    if data.startswith(b"\xef\xbb\xbf"):
        raise ValueError("Save CSV as UTF-8 without BOM")

    levels = {}
    count = 0
    rows = csv.reader(io.StringIO(data.decode("utf-8"), newline=""), strict=True)

    for number, row in enumerate(rows, 1):
        level = check_row(row, number)
        levels[level] = levels.get(level, 0) + 1
        count += 1

    if not count:
        raise ValueError("CSV is empty")

    return {"records": count, "levels": levels}


def generate_header(data, symbol=SYMBOL, width=76):
    describe_csv(data)

    if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", symbol):
        raise ValueError("Invalid C variable name")

    if width < 4 or width % 4:
        raise ValueError("Line width must be a positive multiple of 4")

    compressed = gzip.compress(data, compresslevel=9, mtime=0)
    encoded = base64.b64encode(compressed).decode("ascii")
    lines = [
        "#ifndef DONID_DATA_H",
        "#define DONID_DATA_H",
        "",
        "// Generated by devtools/donid_data.py",
        f"static const char {symbol}[] =",
    ]

    for offset in range(0, len(encoded), width):
        lines.append(f'\t"{encoded[offset : offset + width]}\\n"')

    lines.extend([";", "", "#endif", ""])
    return "\r\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser()
    commands = parser.add_subparsers(dest="command", required=True)

    read = commands.add_parser("read", help="read a header into CSV")
    read.add_argument("header", type=Path)
    read.add_argument("--output", "-o", type=Path, required=True)

    generate = commands.add_parser("generate", help="create a header from CSV")
    generate.add_argument("csv", type=Path)
    generate.add_argument("--output", "-o", type=Path, required=True)

    args = parser.parse_args(argv)

    try:
        if args.command == "read":
            data = decode_header(args.header.read_text(encoding="utf-8-sig"))
            args.output.write_bytes(data)

        else:
            data = args.csv.read_bytes()
            header = generate_header(data)
            args.output.write_bytes(header.encode("ascii"))

        summary = describe_csv(data)
        print(f"Players: {summary['records']}")
        print(f"Bans: {summary['levels'].get(-1, 0)}")
    except (ValueError, OSError, csv.Error, EOFError, zlib.error) as error:
        parser.error(str(error))

    return 0


if __name__ == "__main__":
    sys.exit(main())
